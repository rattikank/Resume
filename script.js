/* Language switch */

function setLang(lang) {
    if (!TEXT[lang]) lang = "en";

    document.documentElement.lang = lang;
    document.title = TEXT[lang].page_title;

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
        const value = TEXT[lang][el.dataset.i18n];
        if (value !== undefined) el.textContent = value;
    });

    document.querySelectorAll(".lang-switch button").forEach(function (btn) {
        btn.setAttribute("aria-pressed", String(btn.dataset.lang === lang));
    });

    try { localStorage.setItem("lang", lang); } catch (e) {}
}

function initialLang() {
    try {
        const saved = localStorage.getItem("lang");
        if (saved && TEXT[saved]) return saved;
    } catch (e) {}
    return (navigator.language || "").toLowerCase().startsWith("th") ? "th" : "en";
}

document.querySelectorAll(".lang-switch button").forEach(function (btn) {
    btn.addEventListener("click", function () { setLang(btn.dataset.lang); });
});

setLang(initialLang());


/* ---------- Modals ---------- */

function openModal(modal) {
    modal.classList.add("active");
    modal.setAttribute("aria-hidden", "false");
    document.body.classList.add("modal-open");
}

function closeModal(modal) {
    modal.classList.remove("active");
    modal.setAttribute("aria-hidden", "true");
    if (!document.querySelector(".modal.active, .lightbox.active")) {
        document.body.classList.remove("modal-open");
    }
}

document.querySelectorAll("[data-open]").forEach(function (btn) {
    btn.addEventListener("click", function () {
        openModal(document.getElementById(btn.dataset.open));
    });
});

/* ---------- Resume (Thai / English) ---------- */

const RESUME_FILES = {
    en: "img/Rattikan_Kankaew_Resume.pdf",
    th: "img/Rattikan_Kankaew_Resume_TH.pdf"
};

function setResume(lang) {
    if (!RESUME_FILES[lang]) lang = "en";
    const file = RESUME_FILES[lang];

    document.getElementById("resumeFrame").src = file;
    document.getElementById("resumeDownload").href = file;
    document.getElementById("resumeOpen").href = file;

    document.querySelectorAll(".resume-tabs button").forEach(function (btn) {
        btn.setAttribute("aria-pressed", String(btn.dataset.resume === lang));
    });
}

document.querySelectorAll(".resume-tabs button").forEach(function (btn) {
    btn.addEventListener("click", function () { setResume(btn.dataset.resume); });
});

document.getElementById("resumeBtn").addEventListener("click", function () {
    // Open with the resume that matches the site's current language
    setResume(document.documentElement.lang === "th" ? "th" : "en");
    openModal(document.getElementById("resumeModal"));
});

document.querySelectorAll(".modal, .lightbox").forEach(function (modal) {
    modal.addEventListener("click", function (e) {
        if (e.target === modal || e.target.closest("[data-close]")) closeModal(modal);
    });
});


/* ---------- Image lightbox ---------- */

const lightbox = document.getElementById("lightbox");
const lightboxImg = document.getElementById("lightbox-image");
const lightboxCaption = document.getElementById("lightbox-caption");

document.querySelectorAll("img[data-zoom]").forEach(function (img) {
    img.addEventListener("click", function () {
        const caption = img.closest("figure").querySelector("figcaption");
        lightboxImg.src = img.src;
        lightboxImg.alt = img.alt;
        lightboxCaption.textContent = caption ? caption.textContent : img.alt;
        openModal(lightbox);
    });
});


/* ---------- Esc key: close the top-most layer ---------- */

document.addEventListener("keydown", function (e) {
    if (e.key !== "Escape") return;
    const top = lightbox.classList.contains("active")
        ? lightbox
        : document.querySelector(".modal.active");
    if (top) closeModal(top);
});
